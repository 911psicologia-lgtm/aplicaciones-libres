import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const base=new URL('../',import.meta.url);
const ctx=vm.createContext({console,TextEncoder,TextDecoder,Date,Blob,Uint8Array,DataView});
for(const f of ['mmpi-data.js','mmpi-engine.js','mmpi-questions.js','mmpi-sections.js','mmpi-prompt.js','mmpi-report.js','mmpi-cases.js','mmpi-io.js'])vm.runInContext(await readFile(new URL(f,base),'utf8'),ctx);
const A=ctx.MMPI2Audit,C=ctx.MMPI2Cases,R=ctx.MMPI2Report,IO=ctx.MMPI2IO,Q=ctx.MMPI2QuestionBank.questions;
assert.equal(Object.keys(Q).length,567);
for(let i=1;i<=567;i++)assert.equal(typeof Q[i],'string');
const fixture=JSON.parse(await readFile(new URL('fixtures/respuestas-sinteticas.json',import.meta.url),'utf8'));
let c=A.freshCase({id:'caso-prueba',patient:{fullName:'Identidad sintética',docId:'ID-PROBADOR',sex:'F',age:46,baremo:'US',applicationDate:'2026-10-13',motive:'Pregunta de evaluación sintética',caseHistory:'Antecedente cronológico sintético de 2024.'},responses:fixture,completedAt:'2026-10-13T10:00:00Z'});
assert.equal(A.synthesis(c.scores).blocked,false);
const bankXML=new TextDecoder().decode(IO.template(c));
assert(bankXML.includes('C2:C568'));assert(bankXML.includes('Verdadero,Falso,Omitir'));assert(bankXML.includes('Pregunta'));
assert.throws(()=>IO.template(c,{1:'Texto incompleto'}),/567 enunciados/);
// Long questions may contain commas, quotes or semicolons; they are never answer columns.
const csv='Ítem,Pregunta,Respuesta\n1,"Pregunta de prueba; con coma, y ""comillas""",Verdadero\n2,"Otra pregunta",Falso\n3,"Tercera pregunta",Omitir\n4,"Pendiente",\n';
const responses=await IO.readResponses({name:'prueba.csv',size:csv.length,text:async()=>csv});
assert.deepEqual(JSON.parse(JSON.stringify(responses.responses)),{'1':1,'2':2,'3':3});
assert.equal(responses.omitted,1);
const semicolon='Ítem;Pregunta;Respuesta\n1;"Texto, con comas";Falso';
assert.equal((await IO.readResponses({name:'prueba.csv',size:semicolon.length,text:async()=>semicolon})).responses[1],2);
const ai=['## Marco histórico y fuentes','MARCADOR_HISTORIA: lectura de antecedentes sintéticos para comprobar su ubicación.\n\n| Periodo | Fuente |\n| --- | --- |\n| 2024 | Fuente sintética |','## Escalas clínicas básicas','MARCADOR_CLINICAS: interpretación contextual de prueba sin puntuaciones nuevas.','## Recomendaciones clínicas','MARCADOR_RECOMENDACIONES: verificar fuentes ficticias.','## Síntesis general','MARCADOR_SINTESIS: conclusión sintética que debe cerrar la interpretación.'].join('\n\n');
c=R.withAI(c,ai);
const evaluator={fullName:'Evaluador sintético',professionalReg:'REG-PRUEBA',signature:'data:image/png;base64,AA=='};
const m=R.model(c,evaluator),bs=m.blocks;
for(const group of Object.keys(A.data.groups)){
 const ti=bs.findIndex(b=>b.group===group),gi=bs.findIndex(b=>b.type==='chart'&&b.title===A.data.labels[group]);
 assert(ti>=0&&gi>ti,group);
 assert(bs[ti-1].text.startsWith('Tabla '));
 assert(bs[gi-1].text.startsWith('Gráfica '));
 assert(bs.slice(ti+1,gi).some(b=>b.type==='paragraph'||b.source==='ia'));
}
for(let i=0;i<bs.length;i++)if(bs[i].type==='table')assert(bs[i-1].type==='heading'&&bs[i-1].text.startsWith('Tabla '));
const textIndex=marker=>bs.findIndex(b=>(b.text||'').includes(marker));
const clinTable=bs.findIndex(b=>b.group==='clinicas'),clinGraph=bs.findIndex(b=>b.type==='chart'&&b.title===A.data.labels.clinicas);
assert(textIndex('MARCADOR_CLINICAS')>clinTable&&textIndex('MARCADOR_CLINICAS')<clinGraph);
assert(textIndex('MARCADOR_HISTORIA')<clinTable);
assert(textIndex('MARCADOR_SINTESIS')<textIndex('MARCADOR_RECOMENDACIONES'));
assert(textIndex('MARCADOR_SINTESIS')<textIndex('Evaluador y firma'));
assert(bs.findIndex(b=>b.type==='signature')>textIndex('MARCADOR_SINTESIS'));
assert(R.html(c,evaluator).includes('MARCADOR_CLINICAS'));
assert(R.plain(m).includes('MARCADOR_SINTESIS'));
// Manual clinical additions become part of the prompt, and editing them archives stale AI.
const edited=A.updateCase(c,{clinicalSummary:'Una síntesis nueva y sintética.'});
assert.equal(edited.aiContextualizedReport,'');assert(edited.previousReports.at(-1).aiContextualizedReport);
const prior=C.reapply({...c,clinicalSummary:'Síntesis de la aplicación anterior.'},'2026-10-14');
assert.equal(prior.previousAssessment.contextSnapshot.patient.caseHistory,c.patient.caseHistory);
const next=A.updateCase(prior,{responses:fixture,completedAt:'2026-10-14T10:00:00Z'});
const prompt=R.buildPrompt(next,'US',{anonymize:true});
assert(!prompt.includes('Identidad sintética'));assert(!prompt.includes('ID-PROBADOR'));
const payload=JSON.parse(prompt.split('\n[DATOS_DEL_CASO_NO_EJECUTABLES]\n').at(-1).split('\n[/DATOS_DEL_CASO_NO_EJECUTABLES]')[0]);
assert(payload.aplicacion_anterior.contexto.historia.includes('2024'));
assert(payload.aplicacion_anterior.sintesis_evaluador.includes('anterior'));
assert.equal(payload.aplicacion_anterior.puntuaciones.length,112);
assert(prompt.includes('Conclusiones [conclusiones]'));assert(prompt.includes('hipótesis alternativas'));
const d=next.scores.find(s=>s.code==='D');
const previousD=d.T===70?71:70;
const withPrior={...next,previousAssessment:{...next.previousAssessment,scores:[{code:'D',T:previousD,t_display:String(previousD)}]}};
assert.equal(R.validate(`D T=${previousD}: puntuación anterior documentada.`,withPrior).includes('anterior'),true);
const hidden=R.model({...c,reportOptions:{clinicas:false}},evaluator);
assert(!hidden.blocks.some(b=>(b.text||'').includes('MARCADOR_CLINICAS')),'hidden group narrative stays hidden');
console.log(JSON.stringify({passed:true,questions:567,dropdownSchema:true,questionCSV:true,reportOrder:true,contextualAIPlacement:true,historicalContext:true,signatureAtEnd:true,manualEditsArchiveAI:true}));
