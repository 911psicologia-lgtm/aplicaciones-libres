const fs=require('fs'),vm=require('vm'),path=require('path');
const root=path.join(__dirname,'..');
const store=new Map();
const localStorage={getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,String(v)),removeItem:k=>store.delete(k)};
const ctx={window:{},localStorage,console,Date,JSON,Math}; ctx.window.window=ctx.window; ctx.window.localStorage=localStorage;
vm.createContext(ctx);
for(const f of ['config.js','storage.js','economy.js']) vm.runInContext(fs.readFileSync(path.join(root,'js',f),'utf8'),ctx,{filename:f});
const C=ctx.window.SF.config,E=ctx.window.SF.economy;
if(C.VERSION!=='0.6.1') throw new Error('wrong version');
let p=E.state();
if(p.coins!==120||p.level!==1) throw new Error('starter economy missing');
let cat=E.catalog();
const repair=cat.find(x=>x.id==='repair'),shield=cat.find(x=>x.id==='shield'),missile=cat.find(x=>x.id==='missile');
if(!repair.affordable||!shield.affordable||missile.levelOk) throw new Error('level/affordability gating wrong');
const buy=E.buy('repair'); if(!buy.ok||E.inventoryCount('heal')!==1) throw new Error('purchase failed');
E.add(300,500); p=E.state(); if(p.level<2) throw new Error('xp leveling failed');
E.grantBossPowers(['missile','shield','overdrive'],1); p=E.state();
if(!p.bossPowers.missile||E.inventoryCount('missile')<1) throw new Error('boss power inheritance failed');
if(!E.consume('missile')||E.inventoryCount('missile')!==0) throw new Error('inventory consume failed');
const game=fs.readFileSync(path.join(root,'js','game.js'),'utf8');
const main=fs.readFileSync(path.join(root,'js','main.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'css','main.css'),'utf8');
for(const token of ['updateBossSupply','grantBossPowers','useInventoryPower','profileWeaponMul','profilePowerMul']) if(!game.includes(token)) throw new Error('missing game token '+token);
for(const token of ['requestFullscreenSafe','toggleFullscreen','shopOverlay','data-buy','data-use']) if(!main.includes(token)&&!html.includes(token)) throw new Error('missing UI/fullscreen token '+token);
if(!css.includes('.shop-item.affordable')||!css.includes('rgba(255,225,55')) throw new Error('yellow neon affordability missing');
console.log('ECONOMY SHOP v0.6.0 PASS',{level:p.level,coins:p.coins,bestStreak:p.bestStreak});
