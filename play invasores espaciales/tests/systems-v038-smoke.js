const fs=require('fs'),vm=require('vm'),path=require('path');
const root=path.resolve(__dirname,'..');
const sandbox={window:{SF:{}},performance:{now:()=>0},console}; sandbox.window.window=sandbox.window;
vm.createContext(sandbox); vm.runInContext(fs.readFileSync(path.join(root,'js/config.js'),'utf8'),sandbox);
const C=sandbox.window.SF.config;
if(C.VERSION!=='0.6.7') throw new Error('wrong version');
if(!C.sectorMutators?.sequence?.length || C.sectorMutators.sequence.length<5) throw new Error('sector mutators missing');
if(!C.eliteVariants?.classes?.length || C.eliteVariants.classes.length<3) throw new Error('elite variants missing');
if(!C.tacticalObjectives?.pools || Object.keys(C.tacticalObjectives.pools).length<4) throw new Error('objective pools missing');
if(!C.fusion?.combos?.length || C.fusion.combos.length<3) throw new Error('fusion system missing');
if(!C.powers?.drone || !C.allyDrone) throw new Error('ally drone missing');
if(!C.bossIdentity.patterns.some(b=>b.reward.includes('drone'))) throw new Error('boss drone relic missing');
const game=fs.readFileSync(path.join(root,'js/game.js'),'utf8');
for(const token of ['selectSectorMutator','initObjective','completeObjective','updateFusion','updateAllyDrone','renderAllyDrone','eliteClass','mutatorScoreMul']) if(!game.includes(token)) throw new Error('missing '+token);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
for(const id of ['hudObjective','hudFusion','hudMutator']) if(!html.includes(`id="${id}"`)) throw new Error('HUD missing '+id);
console.log('V0.3.9.1 SYSTEMS SMOKE OK',{mutators:C.sectorMutators.sequence.length,elites:C.eliteVariants.classes.length,objectives:Object.keys(C.tacticalObjectives.pools||{}).length,fusions:C.fusion.combos.length});
